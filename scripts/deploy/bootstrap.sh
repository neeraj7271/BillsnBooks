#!/usr/bin/env bash
set -euo pipefail

# Antigravity Books - Production Server Bootstrap Script
# Target OS: Ubuntu 22.04+ / Debian 12 / RHEL 9

echo "=== 🚀 Initializing Antigravity Books Production Stack ==="

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/../.." && pwd)"
cd "${ROOT_DIR}"

# 1. Verify Docker and Docker Compose plugin
if ! command -v docker &> /dev/null; then
    echo "📦 Docker not detected. Installing Docker via official convenience script..."
    curl -fsSL https://get.docker.com -o /tmp/get-docker.sh
    sh /tmp/get-docker.sh
    systemctl enable --now docker
fi

if ! docker compose version &> /dev/null; then
    echo "❌ docker compose (v2 plugin) is required. Please install docker-compose-plugin."
    exit 1
fi

# 2. Generate .env.production if not present
if [ ! -f .env.production ]; then
    echo "⚙️ Creating .env.production from template..."
    cp apps/api/.env.example .env.production

    # Generate high-entropy production secrets (>= 32 chars)
    JWT_SECRET_GEN=$(openssl rand -base64 48 | tr -dc 'a-zA-Z0-9' | head -c 48)
    JWT_REFRESH_GEN=$(openssl rand -base64 48 | tr -dc 'a-zA-Z0-9' | head -c 48)
    ENC_KEY_GEN=$(openssl rand -base64 48 | tr -dc 'a-zA-Z0-9' | head -c 32)
    APP_PASS_GEN=$(openssl rand -base64 32 | tr -dc 'a-zA-Z0-9' | head -c 24)
    PG_ADMIN_PASS=$(openssl rand -base64 32 | tr -dc 'a-zA-Z0-9' | head -c 24)
    S3_PASS_GEN=$(openssl rand -base64 32 | tr -dc 'a-zA-Z0-9' | head -c 24)

    sed -i.bak \
        -e "s|CHANGE_ME_GENERATE_AT_LEAST_32_RANDOM_CHARS!|${JWT_SECRET_GEN}|g" \
        -e "s|CHANGE_ME_IN_PRODUCTION|${APP_PASS_GEN}|g" \
        -e "s|CHANGE_MINIO_SECRET_KEY|${S3_PASS_GEN}|g" \
        .env.production
    rm -f .env.production.bak

    cat <<EOF >> .env.production

# Autogenerated Cluster Secrets
POSTGRES_ADMIN_USER=postgres
POSTGRES_ADMIN_PASSWORD=${PG_ADMIN_PASS}
DATABASE_PASSWORD=${APP_PASS_GEN}
JWT_SECRET=${JWT_SECRET_GEN}
JWT_REFRESH_SECRET=${JWT_REFRESH_GEN}
ENCRYPTION_KEY=${ENC_KEY_GEN}
S3_SECRET_KEY=${S3_PASS_GEN}

# Domain & Proxy
APP_DOMAIN=app.yourdomain.com
API_DOMAIN=api.yourdomain.com
STORAGE_DOMAIN=storage.yourdomain.com
ACME_EMAIL=admin@yourdomain.com
EOF

    chmod 600 .env.production
    echo "✅ .env.production generated with 600 permissions."
else
    echo "ℹ️ Existing .env.production found. Preserving configuration."
fi

# 3. Spin up Storage & Database first
echo "🐘 Launching core data services (Postgres, Redis, MinIO)..."
docker compose -f docker/docker-compose.prod.yml up -d postgres redis minio

echo "⏳ Waiting for database readiness..."
until docker compose -f docker/docker-compose.prod.yml exec -T postgres pg_isready -U postgres > /dev/null 2>&1; do
    sleep 2
done

# 4. Run database migrations in one-shot task
echo "🔄 Executing schema migrations and extensions..."
docker compose -f docker/docker-compose.prod.yml run --rm --no-deps api node apps/api/dist/src/database/migration-runner.js || true

# 5. Launch full application stack
echo "🌐 Starting Application services and Caddy TLS reverse proxy..."
docker compose -f docker/docker-compose.prod.yml up -d --build

echo "✅ Antigravity Books Production Stack is up and running!"
echo "👉 Web URL: https://\$(grep APP_DOMAIN .env.production | cut -d '=' -f2)"
echo "👉 API URL: https://\$(grep API_DOMAIN .env.production | cut -d '=' -f2)"
